export function punishmentKind(punishment: string | undefined): PunishmentKind {
  if (!punishment) return "unknown";
  const p = punishment.toLowerCase();
  if (p.includes("???")) return "unknown";
  if (p.startsWith("бан")) return "ban";
  if (p.includes("модератор")) return "moderator";
  if (p.includes("мут")) return "mute";
  return "unknown";
}
